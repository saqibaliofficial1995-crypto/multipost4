import os
import datetime
import requests

REPORTS_DIR = os.path.join(os.path.dirname(os.path.dirname(os.path.abspath(__file__))), "reports")

def run_weekly_analytics(access_token):
    print("[analytics] Generating 7-day YouTube analytics report...", flush=True)
    os.makedirs(REPORTS_DIR, exist_ok=True)
    
    today = datetime.date.today()
    start_date = today - datetime.timedelta(days=7)
    
    url = "https://youtubeanalytics.googleapis.com/v2/reports"
    params = {
        "ids": "channel==MINE",
        "startDate": start_date.isoformat(),
        "endDate": today.isoformat(),
        "metrics": "views,estimatedMinutesWatched,subscribersGained"
    }
    headers = {"Authorization": f"Bearer {access_token}"}
    
    res = requests.get(url, headers=headers, params=params, timeout=20)
    views, minutes, subs = 0, 0, 0
    if res.status_code == 200:
        rows = res.json().get("rows", [])
        if rows:
            views, minutes, subs = rows[0]

    report_content = f"""# Weekly Channel Analytics Report (Channel 4)

**Reporting Window:** {start_date.isoformat()} to {today.isoformat()}  
**Channel:** Jennifer Castro (`UCZondNewuq0gMQIxEaZOk2g`)

---

## Performance Summary
- **Total Views:** {views:,}
- **Watch Time (Minutes):** {minutes:,.1f}
- **Net Subscribers Gained:** {subs}

---
*Report auto-generated by Channel 4 Cloud Automation.*
"""

    report_file = os.path.join(REPORTS_DIR, f"weekly_report_{today.isoformat()}.md")
    with open(report_file, "w", encoding="utf-8") as f:
        f.write(report_content)

    print(f"[analytics] Weekly report generated successfully at {report_file}", flush=True)
